  await expect(locked.getByRole('heading', { name: 'Original directions' })).toBeVisible();
  await expect(locked.getByRole('button', { name: 'Edit instructions' })).toHaveCount(0);
  await locked.getByRole('button', { name: 'Close' }).click();
